package com.requestmanagement.backend.statushistory;

import java.time.LocalDateTime;

import com.requestmanagement.backend.request.Request;
import com.requestmanagement.backend.request.RequestStatus;
import com.requestmanagement.backend.user.User;
import com.requestmanagement.backend.projectstatus.ProjectStatusColumn;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;

@Entity
@Table(name = "status_history")
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class StatusHistory {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "history_id")
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "request_id", nullable = false)
    private Request request;

    @Enumerated(EnumType.STRING)
    @Column(name = "old_status", length = 30)
    private RequestStatus oldStatus;

    @Enumerated(EnumType.STRING)
    @Column(name = "new_status", nullable = false, length = 30)
    private RequestStatus newStatus;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "old_project_status_id")
    private ProjectStatusColumn oldProjectStatus;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "new_project_status_id")
    private ProjectStatusColumn newProjectStatus;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "changed_by", nullable = false)
    private User changedBy;

    @Column(name = "change_note", columnDefinition = "TEXT")
    private String changeNote;

    @Column(name = "changed_at", nullable = false)
    private LocalDateTime changedAt;

    public static StatusHistory create(Request request, RequestStatus oldStatus,
                                       RequestStatus newStatus, User changedBy, String note) {
        StatusHistory history = new StatusHistory();
        history.request = request;
        history.oldStatus = oldStatus;
        history.newStatus = newStatus;
        history.changedBy = changedBy;
        history.changeNote = note;
        history.changedAt = LocalDateTime.now();
        return history;
    }

    public static StatusHistory createProject(Request request, ProjectStatusColumn oldStatus,
                                               ProjectStatusColumn newStatus, User changedBy, String note) {
        StatusHistory history = new StatusHistory();
        history.request = request;
        history.oldStatus = oldStatus.getSemanticKey() == null ? null : RequestStatus.valueOf(oldStatus.getSemanticKey().name());
        history.newStatus = newStatus.getSemanticKey() == null ? null : RequestStatus.valueOf(newStatus.getSemanticKey().name());
        history.oldProjectStatus = oldStatus;
        history.newProjectStatus = newStatus;
        history.changedBy = changedBy;
        history.changeNote = note;
        history.changedAt = LocalDateTime.now();
        return history;
    }

    public void refreshAutoGeneratedProjectNote(Long renamedStatusId, String previousName) {
        if (oldProjectStatus == null || newProjectStatus == null || changeNote == null) return;
        String oldNameBeforeRename = oldProjectStatus.getId().equals(renamedStatusId)
                ? previousName : oldProjectStatus.getName();
        String newNameBeforeRename = newProjectStatus.getId().equals(renamedStatusId)
                ? previousName : newProjectStatus.getName();
        String previousDefault = "Status changed from " + oldNameBeforeRename + " to " + newNameBeforeRename + ".";
        if (changeNote.equals(previousDefault)) {
            changeNote = "Status changed from " + oldProjectStatus.getName()
                    + " to " + newProjectStatus.getName() + ".";
        }
    }

}
